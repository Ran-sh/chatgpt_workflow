#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const packageRoot = path.resolve(here, '..');
const manifestRelativePath = 'docs/.agent-workflow-install.json';

function fail(message, code = 1) {
  console.error(`agent-workflow: ${message}`);
  process.exit(code);
}

function readText(file) {
  return fs.readFileSync(file, 'utf8');
}

function readJson(file) {
  return JSON.parse(readText(file));
}

function ensureRelativeSafe(rel) {
  if (!rel || path.isAbsolute(rel)) fail(`unsafe managed path: ${rel}`);
  const normalized = path.normalize(rel);
  if (normalized === '..' || normalized.startsWith(`..${path.sep}`)) {
    fail(`unsafe managed path: ${rel}`);
  }
  return normalized;
}

function detectProject(target) {
  const facts = {
    languages: [],
    package_manager: null,
    build_command: null,
    test_command: null,
    ci: []
  };

  const has = (rel) => fs.existsSync(path.join(target, rel));
  if (has('tsconfig.json')) facts.languages.push('TypeScript');
  if (has('package.json')) {
    facts.languages.push('JavaScript');
    try {
      const pkg = readJson(path.join(target, 'package.json'));
      if (pkg.scripts?.build) facts.build_command = `${detectPackageManager(target) ?? 'npm'} run build`;
      if (pkg.scripts?.test) facts.test_command = `${detectPackageManager(target) ?? 'npm'} test`;
      if (typeof pkg.packageManager === 'string') {
        facts.package_manager = pkg.packageManager.split('@')[0];
      }
    } catch {
      // Keep detection conservative if package.json is malformed.
    }
  }
  if (has('pyproject.toml') || has('requirements.txt')) facts.languages.push('Python');
  if (has('go.mod')) facts.languages.push('Go');
  if (has('Cargo.toml')) facts.languages.push('Rust');
  facts.languages = [...new Set(facts.languages)];
  facts.package_manager ??= detectPackageManager(target);

  const workflows = path.join(target, '.github', 'workflows');
  if (fs.existsSync(workflows) && fs.statSync(workflows).isDirectory()) {
    facts.ci = fs.readdirSync(workflows)
      .filter((name) => /\.ya?ml$/i.test(name))
      .sort()
      .map((name) => `.github/workflows/${name}`);
  }
  return facts;
}

function detectPackageManager(target) {
  if (fs.existsSync(path.join(target, 'pnpm-lock.yaml'))) return 'pnpm';
  if (fs.existsSync(path.join(target, 'yarn.lock'))) return 'yarn';
  if (fs.existsSync(path.join(target, 'bun.lockb')) || fs.existsSync(path.join(target, 'bun.lock'))) return 'bun';
  if (fs.existsSync(path.join(target, 'package-lock.json'))) return 'npm';
  return null;
}

function projectSection(facts) {
  const languages = facts.languages.length ? facts.languages.join(', ') : 'not confidently detected';
  const ci = facts.ci.length ? facts.ci.join(', ') : 'not detected';
  return `\n\n## Generated project adapter\n\nThis section was generated by the agent-workflow installer. Treat detected values as repository facts to verify, never as permission to invent missing commands.\n\n- Languages: ${languages}\n- Package manager: ${facts.package_manager ?? 'not detected'}\n- Build command: ${facts.build_command ?? 'not detected; do not invent one'}\n- Test command: ${facts.test_command ?? 'not detected; do not invent one'}\n- CI: ${ci}\n\nTask permissions still come only from the active Task Contract. Executor choice does not change permissions.\n`;
}

function copyPlan(target, facts) {
  return [
    ['templates/agent-workflow.md', 'docs/agent-workflow.md', projectSection(facts)],
    ['templates/agent-short-triggers.md', 'docs/agent-short-triggers.md', ''],
    ['templates/agent-tasks/README.md', 'docs/agent-tasks/README.md', ''],
    ['templates/agent-tasks/TEMPLATE_IMPLEMENT.md', 'docs/agent-tasks/TEMPLATE_IMPLEMENT.md', ''],
    ['templates/agent-tasks/TEMPLATE_TEST_ONLY.md', 'docs/agent-tasks/TEMPLATE_TEST_ONLY.md', ''],
    ['templates/agent-tasks/TEMPLATE_REVIEW_ONLY.md', 'docs/agent-tasks/TEMPLATE_REVIEW_ONLY.md', ''],
    ['templates/agent-results/README.md', 'docs/agent-results/README.md', ''],
    ['schema/task-contract.schema.json', '.agent-workflow/schema/task-contract.schema.json', ''],
    ['schema/result-contract.schema.json', '.agent-workflow/schema/result-contract.schema.json', ''],
    ['validator/validate-contract.mjs', '.agent-workflow/validator/validate-contract.mjs', '']
  ].map(([source, destination, suffix]) => ({
    source: path.join(packageRoot, source),
    destination: ensureRelativeSafe(destination),
    suffix
  }));
}

function install(targetArg) {
  const target = path.resolve(targetArg ?? process.cwd());
  if (!fs.existsSync(target) || !fs.statSync(target).isDirectory()) {
    fail(`target directory does not exist: ${target}`);
  }

  const manifestPath = path.join(target, manifestRelativePath);
  if (fs.existsSync(manifestPath)) {
    fail(`workflow is already installed (${manifestRelativePath} exists)`);
  }

  const facts = detectProject(target);
  const plan = copyPlan(target, facts);
  const missingSources = plan.filter((item) => !fs.existsSync(item.source));
  if (missingSources.length) {
    fail(`package is incomplete; missing source: ${missingSources[0].source}`);
  }

  const conflicts = plan
    .map((item) => item.destination)
    .filter((rel) => fs.existsSync(path.join(target, rel)));
  if (fs.existsSync(manifestPath)) conflicts.push(manifestRelativePath);
  if (conflicts.length) {
    fail(`refusing to overwrite pre-existing files:\n- ${conflicts.join('\n- ')}`);
  }

  for (const item of plan) {
    const destination = path.join(target, item.destination);
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.writeFileSync(destination, readText(item.source) + item.suffix, 'utf8');
  }

  const version = readText(path.join(packageRoot, 'VERSION')).trim();
  const manifest = {
    schema_version: 1,
    source_repository: 'Ran-sh/chatgpt_workflow',
    workflow_version: version,
    project: path.basename(target),
    installed_at: new Date().toISOString(),
    generated_files: [...plan.map((item) => item.destination), manifestRelativePath],
    project_facts: facts
  };

  fs.mkdirSync(path.dirname(manifestPath), { recursive: true });
  fs.writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');

  console.log(`Installed Agent Workflow ${version} into ${target}`);
  console.log(`Managed files: ${manifest.generated_files.length}`);
  console.log('No ACTIVE task was created.');
}

function validate(kind, fileArg) {
  if (!['task', 'result'].includes(kind)) {
    fail('validate requires kind: task or result');
  }
  if (!fileArg) fail('validate requires a contract file path');
  const file = path.resolve(fileArg);
  if (!fs.existsSync(file)) fail(`contract file does not exist: ${file}`);

  const validator = path.join(packageRoot, 'validator', 'validate-contract.mjs');
  const result = spawnSync(process.execPath, [validator, kind, file], {
    stdio: 'inherit'
  });
  process.exit(result.status ?? 1);
}

function removeEmptyParents(target, rel) {
  const stop = path.resolve(target);
  let current = path.dirname(path.join(target, rel));
  while (current.startsWith(stop + path.sep)) {
    if (!fs.existsSync(current)) {
      current = path.dirname(current);
      continue;
    }
    if (fs.readdirSync(current).length !== 0) break;
    fs.rmdirSync(current);
    current = path.dirname(current);
  }
}

function uninstall(targetArg) {
  const target = path.resolve(targetArg ?? process.cwd());
  const manifestPath = path.join(target, manifestRelativePath);
  if (!fs.existsSync(manifestPath)) {
    fail(`no installation manifest found at ${manifestRelativePath}`);
  }

  let manifest;
  try {
    manifest = readJson(manifestPath);
  } catch (error) {
    fail(`cannot parse installation manifest: ${error.message}`);
  }

  if (!Array.isArray(manifest.generated_files)) {
    fail('installation manifest has no generated_files array');
  }

  const files = manifest.generated_files.map(ensureRelativeSafe);
  if (!files.includes(manifestRelativePath)) files.push(manifestRelativePath);

  // Delete the manifest last so an interrupted uninstall remains recoverable.
  const ordered = files.filter((rel) => rel !== manifestRelativePath);
  ordered.push(manifestRelativePath);

  for (const rel of ordered) {
    const absolute = path.join(target, rel);
    if (fs.existsSync(absolute) && fs.statSync(absolute).isFile()) {
      fs.unlinkSync(absolute);
      removeEmptyParents(target, rel);
    }
  }

  console.log(`Removed Agent Workflow managed files from ${target}`);
  console.log('Pre-existing and unmanaged project files were not touched.');
}

function help() {
  console.log(`agent-workflow\n\nUsage:\n  agent-workflow install [target]\n  agent-workflow validate task <file>\n  agent-workflow validate result <file>\n  agent-workflow uninstall [target]\n  agent-workflow --version\n\nThe installer never creates an ACTIVE task and refuses to overwrite pre-existing managed paths.`);
}

const args = process.argv.slice(2);
if (args[0] === '--version' || args[0] === '-v') {
  console.log(readText(path.join(packageRoot, 'VERSION')).trim());
  process.exit(0);
}

switch (args[0]) {
  case 'install':
    install(args[1]);
    break;
  case 'validate':
    validate(args[1], args[2]);
    break;
  case 'uninstall':
    uninstall(args[1]);
    break;
  case 'help':
  case '--help':
  case '-h':
  case undefined:
    help();
    break;
  default:
    fail(`unknown command: ${args[0]}\nRun agent-workflow --help for usage.`);
}
